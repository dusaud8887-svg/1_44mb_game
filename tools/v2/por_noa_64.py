#!/usr/bin/env python3
# por_noa_64.py — 노아/NØA V2 초상 64×64 (모에 개정판 — 청초하고 아름다운 관리자)
# 브리지 유지: 자홍 수직 베일 / 한쪽 흰 장갑 / 프로필 환 / 완벽하게 정돈된 미소 / 완전 대칭
# 표정: 반개 눈이되 원반 홍채+반짝임으로 '살아있는 경청' — 죽은 눈 금지. 위험은 규칙성에만.
import sys, os, math
sys.path.insert(0, os.path.dirname(__file__))
from pxlib import Grid

g = Grid(64, 64)
CX = 32


def sym(x, y, c, over=True):
    g.set(x, y, c, over)
    g.set(2 * CX - x, y, c, over)


# ---------- 관객 베일 (좌우 동일한 채팅 줄 — 부드럽게, 창살 금지) ----------
chat = [(3, "5"), (2, "6"), (4, "6"), (0, "c"), (3, "6"), (2, "5")]
for sx in (1, 57):
    g.rect(sx, 0, sx + 5, 63, "3")
    y = 3
    for i in range(10):
        ln, col = chat[i % len(chat)]
        if col == "c":
            g.rect(sx + 1, y, sx + 2, y + 1, "c")
        else:
            g.set(sx + 1, y, "c")
            g.run(sx + 2, sx + 2 + ln, y, col)
        y += 6

# ---------- 프로필 아이콘 환 (머리 위 정확한 원호) ----------
for x, y in ((12, 10), (18, 5), (25, 2), (32, 1), (39, 2), (46, 5), (52, 10)):
    g.rect(x, y, x + 1, y + 1, "c")
    g.set(x + 1, y + 1, "b")

# ---------- 머리카락 큰 덩어리 (히메컷 — 검은 플랫 + 자홍 광택) ----------
hair = {6: (24, 40), 7: (20, 44), 8: (18, 46), 9: (16, 48), 10: (15, 49),
        11: (14, 50), 12: (13, 51), 13: (13, 51), 14: (12, 52), 15: (12, 52)}
for y, (x0, x1) in hair.items():
    g.run(x0, x1, y, "2")
for y in range(16, 46):
    g.run(12, 52, y, "2")
# 뒷머리가 어깨 뒤 하단까지
for y in range(46, 64):
    g.run(13, 18, y, "2"); g.run(46, 51, y, "2")
# 광택 — 완벽히 대칭인 자홍 시퀀스
g.run(20, 24, 9, "b"); g.run(40, 44, 9, "b")
g.vrun(15, 18, 40, "b"); g.vrun(49, 18, 40, "b")

# ---------- 얼굴 (넓고 둥근 모에 페이스 — 완전 대칭) ----------
face = {20: (21, 43), 21: (19, 45), 22: (18, 46)}
for y in range(23, 41):
    face[y] = (18, 46)
face.update({41: (19, 45), 42: (21, 43), 43: (24, 40), 44: (28, 36)})
for y, (x0, x1) in face.items():
    g.run(x0, x1, y, "5")

# ---------- 히메컷 앞머리 — 완벽한 일직선 절단 (눈썹 위 1px) ----------
g.rect(12, 12, 52, 21, "2")
g.run(13, 51, 22, "2")
# 사이드락 — 뺨 옆 수직 기둥, 수평 절단
g.rect(12, 22, 17, 46, "2"); g.rect(47, 22, 52, 46, "2")
g.run(12, 17, 46, "3"); g.run(47, 52, 46, "3")

# ---------- 눈 — 반개한 거대 자홍 원반 (경청 + 반짝임, 완전 대칭) ----------
# 밝은 자홍 원반 + 동공 + 큰 하이라이트 — 반개하되 살아 있는 눈
eye = [
    "22222222222",
    "22222222222",
    "22222222222",
    "2ccccccccc2",
    "cc55bbbcccc",
    "cc55bbbcccc",
    "ccccbbbcccc",
    "2ccccccccc2",
    ".2bbbbbbb2.",
    "..2666662..",
]
g.blit(19, 24, eye)
g.blit(34, 24, eye)                                        # 완전 동일 — 그것이 노아다
# 눈썹 — 완만한 대칭
g.run(21, 27, 22, "6", over=False)
g.run(37, 43, 22, "6", over=False)

# ---------- 볼터치 (자홍 — 완벽히 대칭) ----------
g.run(18, 20, 37, "c"); g.run(44, 46, 37, "c")

# ---------- 입 — 정돈된 작은 미소 (양쪽 꼬리 동일 상승) ----------
g.run(30, 34, 40, "2")
sym(29, 39, "2")

# ---------- 목·포멀웨어 (좁은 수직) + 자홍 수직선 + 흰 장갑 ----------
g.rect(29, 45, 35, 48, "5")
g.run(30, 34, 45, "6")
g.rect(26, 49, 38, 50, "2")
sh = {51: (22, 42), 52: (20, 44), 53: (19, 45)}
for y, (x0, x1) in sh.items():
    g.run(x0, x1, y, "2")
g.rect(18, 54, 46, 63, "2")
# 이중 테두리 (PANEL 안쪽 라인 — NØA 선 문법)
for y in range(54, 64):
    sym(19, y, "3")
g.run(20, 44, 54, "3", over=False)
# 자홍 수직선
g.vrun(32, 51, 63, "b"); g.set(32, 53, "c"); g.set(32, 58, "c")
# 흰 장갑 — 가슴 앞에 얹은 한 손 (팔 라인 연결)
g.run(38, 42, 55, "3")
g.blit(37, 56, [
    ".5.5.5",
    "555555",
    "555555",
    ".55555",
])
g.set(39, 57, "6"); g.set(41, 57, "6")
g.run(38, 42, 60, "c")                                     # 커프스

g.save(os.path.join(os.path.dirname(__file__), "..", "..", "assets", "px_v2", "por_noa_64.px"),
       "por_noa_64 — 노아/NØA V2 초상 (모에 개정 — 청초한 경청)")
