#!/usr/bin/env python3
# por_noa_64.py — 노아/NØA V2 초상 64×64 (docs/06 §3, 40 §4 — FIRST MODERATOR 단계)
# 브리지: 자홍 수직 댓글 베일 / 한쪽 흰 장갑 / 프로필 아이콘 환 / 완벽하게 정돈된 미소
# 문법: 완전 대칭·수직선·이중 테두리 (에코의 유기적 비대칭과 정반대) — 대칭이 곧 캐릭터
# 반개한 눈 = 냉소가 아니라 경청. 위험은 얼굴이 아니라 베일·환의 '지나친 규칙성'에만.
import sys, os
sys.path.insert(0, os.path.dirname(__file__))
from pxlib import Grid

g = Grid(64, 64)
CX = 32  # 완전 대칭 축


def sym(x, y, c, over=True):
    g.set(x, y, c, over)
    g.set(2 * CX - x, y, c, over)


# ---------- 관객 베일 (최후방) — 좌우 '완전히 동일한' 채팅 줄 ----------
# 같은 문장·같은 길이·같은 간격이 양쪽에 반복된다 (NØA의 가짜 계정 문법, docs/40 §7)
chat = [(3, "5"), (2, "6"), (4, "6"), (0, "c"), (3, "6"), (2, "5"), (4, "6"), (0, "c")]
for sx in (2, 56):
    g.rect(sx, 0, sx + 5, 63, "3")
    g.vrun(sx, 0, 63, "4"); g.vrun(sx + 5, 0, 63, "4")
    y = 2
    for i in range(10):
        ln, col = chat[i % len(chat)]
        if col == "c":
            g.rect(sx + 1, y, sx + 2, y + 1, "c")      # 프로필 원
            g.run(sx + 3, sx + 4, y, "6")
        else:
            g.set(sx + 1, y, "c")                        # 닉 점
            g.run(sx + 2, sx + 2 + ln, y, col)
        y += 6                                            # 완벽히 균일한 줄 간격
# ---------- 프로필 아이콘 환 (머리 위 정확한 원호, 기계적 등간격) ----------
# 명시적 대칭 원호 — 7개, 머리 위로 정확히 등을 그림 (기계적 등간격)
for x, y in ((13, 12), (18, 6), (24, 2), (32, 0), (40, 2), (46, 6), (51, 12)):
    g.rect(x, y, x + 1, y + 1, "c")
    g.set(x + 1, y + 1, "b")

# ---------- 뒷머리 (히메컷 뒤판 — 어깨 뒤로 곧게) ----------
g.rect(19, 10, 45, 52, "2")
for x in (22, 42):
    g.vrun(x, 14, 50, "b")                               # 대칭 광택선

# ---------- 어깨·재킷 (수직 실루엣 — 좁고 곧게) ----------
sh = {46: (23, 41), 47: (21, 43), 48: (19, 45), 49: (17, 47), 50: (16, 48)}
for y, (x0, x1) in sh.items():
    g.run(x0, x1, y, "2")
g.rect(15, 51, 49, 63, "2")
# 이중 테두리 (NØA 선 문법) — 재킷 외곽 안쪽으로 PANEL 라인
for i, y in enumerate(range(46, 64)):
    x0 = {46: 23, 47: 21, 48: 19, 49: 17, 50: 16}.get(y, 15)
    sym(x0, y, "3")
for y in range(52, 64):
    sym(17, y, "b")                                      # 자홍 파이핑 (이중 테두리 2선째)
# 자홍 수직선 — 가슴 중앙 (브리지)
g.vrun(32, 50, 63, "b"); g.set(32, 50, "c"); g.set(32, 54, "c"); g.set(32, 58, "c")

# ---------- 목·하이칼라 ----------
g.rect(29, 42, 35, 46, "5")
g.run(30, 34, 42, "6")                                   # 턱 그림자 (유일한 피부 음영)
g.rect(27, 46, 37, 48, "2")
g.run(28, 36, 46, "3")                                   # 칼라 상단 라인
g.run(27, 37, 49, "3")                                   # 칼라 하단 라인 — 재킷과 분리
sym(28, 47, "c")                                          # 칼라 자홍 핀 (대칭 2점)

# ---------- 얼굴 (완전 대칭 — 평탄한 완벽함) ----------
face = {14: (26, 38), 15: (25, 39), 16: (25, 39), 17: (24, 40), 18: (24, 40)}
for y in range(19, 34):
    face[y] = (24, 40)
face.update({34: (25, 39), 35: (25, 39), 36: (25, 39), 37: (26, 38), 38: (26, 38),
             39: (27, 37), 40: (28, 36), 41: (29, 35), 42: (30, 34)})
for y, (x0, x1) in face.items():
    g.run(x0, x1, y, "5")

# ---------- 눈 (반개 — 경청. 직선 눈꺼풀 + 프로필 점 하이라이트) ----------
for dx in range(4):                                       # 눈썹 — 완만하고 대칭
    sym(25 + dx, 23, "2")
sym(29, 24, "2")
# 눈: 7폭, y26~30. 윗눈꺼풀 2px 직선(반개), 홍채는 아래 2줄만 보임
# 홍채는 면으로(노이즈 금지), 하이라이트 = 작은 프로필 점 1개 + 보조 점 1개
eye = [
    "2222222",
    "2222222",
    "2c5ccc2",
    "2bcc5b2",
    ".6bbb6.",
]
g.blit(25, 26, eye)
g.blit(33, 26, eye)                                       # 완전 동일 — 그것이 노아다
# 속눈썹 바깥 끝 (대칭)
sym(24, 27, "2")

# ---------- 코·입 (완벽하게 중앙, 양쪽 입꼬리 동일 상승) ----------
g.set(32, 33, "6")
g.run(31, 33, 37, "2")
sym(30, 36, "2")

# ---------- 히메컷 앞머리 — 눈썹 바로 위까지, 완벽한 일직선 절단 ----------
g.rect(21, 5, 43, 21, "2")
g.set(21, 5, "."); g.set(43, 5, ".")                      # 정수리 모서리 라운딩
g.set(21, 6, "."); g.set(43, 6, ".")
g.run(23, 41, 4, "2")
g.run(21, 43, 22, "2")                                    # 절단선 y22 — 눈썹(y23) 1px 위
# 광택 — 대칭 자홍 시퀀스 (기계적으로 정확한 등간격)
g.run(26, 29, 9, "b"); g.run(35, 38, 9, "b")
g.run(24, 25, 10, "b"); g.run(39, 40, 10, "b")
# 사이드락 — 뺨 옆 직선 기둥, 뭉툭한 수평 절단 (PANEL 에지로 뒷머리와 분리)
for x0 in (19, 41):
    g.rect(x0, 12, x0 + 3, 44, "2")
    g.run(x0, x0 + 3, 44, "3")                            # 절단면 라인
    g.vrun(x0 + 3 if x0 == 19 else x0, 14, 43, "3")       # 안쪽(얼굴 쪽) 에지
g.vrun(20, 16, 40, "b"); g.vrun(43, 16, 40, "b")          # 대칭 광택

# ---------- 흰 장갑 (유일한 비대칭 — 가슴에 얹은 한쪽 손, 손끝이 중앙을 향함) ----------
g.blit(34, 50, [
    ".5.5.5.",
    ".5.5.5.",
    "5555555",
    "5555555",
    ".555555",
    "..55555",
])
g.set(35, 52, "6"); g.set(37, 52, "6"); g.set(39, 52, "6")  # 손가락 골 연결부
g.run(36, 40, 56, "c")                                    # 커프스 자홍 라인
g.run(37, 40, 57, "b")

g.save(os.path.join(os.path.dirname(__file__), "..", "..", "assets", "px_v2", "por_noa_64.px"),
       "por_noa_64 — 노아/NØA V2 초상 (FIRST MODERATOR — 깨끗한 관리자)")
