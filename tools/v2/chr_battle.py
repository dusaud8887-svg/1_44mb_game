#!/usr/bin/env python3
# chr_battle.py — V2 전장 스프라이트 3종 (docs/41 §2 규격)
# 에코 24×24 idle / 시크 버퍼 셸 16×16 / 노아 대리체 24×24
# 24×24 명암 3단, 디더 금지, 발 피벗 하단 중앙 (docs/41 §4)
import sys, os
sys.path.insert(0, os.path.dirname(__file__))
from pxlib import Grid

out_dir = os.path.join(os.path.dirname(__file__), "..", "..", "assets", "px_v2")

# ============ 에코 24×24 — idle (관객 쪽으로 열린 자세, 오른손이 신호를 밀어냄) ============
e = Grid(24, 24)
# 끊긴 링 (머리 뒤, 8대구간 — 우상단 끊김)
e.arc(11, 7, 7, -10, 265, "7", dash=(34, 12), thick=1, under=True)
e.set(6, 3, "8")                                          # 점등 1칸 (좌상)
# 머리 — 비대칭: 뷰어-좌로 긴 머리채
e.blit(5, 1, [
    "..8888888.",
    ".888888888",
    "8888888888",
    "8858858887",
    "8852852887",
    "8555555787",
    ".8555557.7",
])
e.blit(4, 8, [
    "78..........",
    "78..........",
    "77..........",
])
e.vrun(5, 8, 13, "8"); e.vrun(6, 8, 12, "7")              # 긴 머리채
e.set(5, 14, "7")
# 몸통 — 흰 재킷, 오른팔이 화면 오른쪽(관객)으로 신호를 밀어냄
e.blit(7, 8, [
    ".5555....",
    "555555...",
    "25555555.",
    ".5555.555",
    ".5555...5",
    ".2552.....",
])
e.set(7, 10, "d")                                         # LIVE 핀 (가슴 좌)
e.set(16, 11, "8"); e.set(17, 12, "8")                    # 밀어낸 신호 (손끝 청록)
# 안감 하이넥
e.vrun(10, 8, 9, "2")
# 하의·다리
e.blit(8, 14, [
    "2222.",
    ".22..",
    ".2.2.",
    ".2.2.",
])
e.run(8, 9, 18, "2"); e.run(11, 12, 18, "2")              # 신발
# 헤드셋 (한쪽)
e.set(14, 4, "2"); e.set(14, 5, "2")
e.save(os.path.join(out_dir, "chr_echo_24_idle.px"),
       "chr_echo_24_idle — 에코 전장체 idle (pivot 10,18 / hand_socket 16,11)")

# ============ 시크 버퍼 셸 16×16 — 외눈 렌즈 + 케이블 꼬리 ============
s = Grid(16, 16)
# 셸 (낮고 둥근 — 감기는 곡선)
s.blit(2, 4, [
    "..444444..",
    ".44444444.",
    "4444444444",
    "4442222444",
    "444299a244",
    "44429aa244",
    "4442222444",
    ".44444444.",
    "..444444..",
])
# 렌즈 하이라이트
s.set(7, 8, "5")
# 케이블 꼬리 — 본체보다 먼저 화면에 들어오는 그 끝
s.set(12, 11, "9"); s.set(13, 12, "9"); s.set(14, 12, "9")
s.set(15, 11, "a")                                        # 커넥터 끝
# 날짜 태그 (셸에 부착)
s.set(3, 5, "a"); s.set(4, 5, "a")
s.outline_selout("4", "3")
s.save(os.path.join(out_dir, "chr_seek_shell_16.px"),
       "chr_seek_shell_16 — 시크 실제 색인 프로세스 (cable_socket 12,11)")

# ============ 노아 대리체 24×24 — 수직 실루엣, 본체는 적게 움직임 ============
n = Grid(24, 24)
# 프로필 환 (머리 위 3점 — 등간격)
for x, y in ((7, 1), (11, 0), (15, 1)):
    n.set(x, y, "c")
# 히메컷 머리 (대칭)
n.blit(7, 2, [
    ".22222222.",
    "2222222222",
    "2222222222",
    "2255555522",
    "2255555522",
    "2255555522",
    "22.5555.22",
])
# 반개 눈 (2px 가로선 + 자홍 1px — 완전 대칭)
n.run(9, 10, 6, "2"); n.run(13, 14, 6, "2")
n.set(10, 7, "c"); n.set(13, 7, "c")
# 사이드락 — 어깨까지 수직 기둥
n.vrun(7, 9, 14, "2"); n.vrun(8, 9, 13, "2")
n.vrun(15, 9, 13, "2"); n.vrun(16, 9, 14, "2")
# 몸 — 좁은 수직 포멀웨어 + 자홍 수직선
n.blit(9, 9, [
    "222222",
    "222222",
    "222222",
    "222222",
    "222222",
    "222222",
    "222222",
    ".2222.",
])
n.vrun(12, 9, 16, "b")                                    # 자홍 수직선
n.set(12, 10, "c")
# 흰 장갑 (한쪽 — 유일한 밝은 점)
n.set(15, 12, "5"); n.set(16, 12, "5")
# 베일 스크롤 라인 (몸 옆 수직 대시 — 본체 대신 움직이는 요소)
n.vrun(5, 10, 12, "b"); n.vrun(19, 10, 12, "b")
n.set(5, 15, "b"); n.set(19, 15, "b")
n.run(10, 13, 17, "2")                                    # 하단
n.save(os.path.join(out_dir, "chr_noa_24_idle.px"),
       "chr_noa_24_idle — 노아 대리체 idle (head_socket 11,4)")
print("battle sprites done")
