#!/usr/bin/env python3
# por_seek_64.py — 시크 웜 V2 초상 64×64 (모에 개정판 — 헬테이커식 스머그 그렘린)
# 브리지 유지: 호박 버퍼 릴 / 읽히지 않는 한쪽 눈 / 리본 케이블 / 날짜 태그 / 송곳니
# 표정: '공손한 집착'을 졸린 스머그 미소로 — 무섭지 않고 얄밉게 귀엽게
import sys, os
sys.path.insert(0, os.path.dirname(__file__))
from pxlib import Grid

g = Grid(64, 64)

# ---------- 깨진 버퍼 릴 (배경 — 불규칙 절단, 2칸 점등) ----------
g.arc(32, 30, 30, -30, 45, "9", dash=(11, 4), thick=2)
g.arc(32, 30, 30, 80, 155, "9", dash=(11, 4), thick=2)
g.arc(32, 30, 30, 200, 265, "9", dash=(11, 4), thick=2)
for a0 in (215, 240):
    g.arc(32, 30, 30, a0, a0 + 8, "a", thick=2)

# ---------- 후드 (크고 둥근 덩어리 — 검은 외곽선 + 슬레이트 플랫) ----------
hood = {5: (22, 42), 6: (18, 46), 7: (16, 48), 8: (14, 50), 9: (13, 51),
        10: (12, 52), 11: (11, 53), 12: (10, 54), 13: (10, 54), 14: (9, 55),
        15: (9, 55), 16: (9, 55)}
for y, (x0, x1) in hood.items():
    g.run(x0, x1, y, "4")
for y in range(17, 48):
    g.run(9, 55, y, "4")
# 후드 외곽선
for y, (x0, x1) in hood.items():
    g.set(x0, y, "2"); g.set(x1, y, "2")
g.run(22, 42, 4, "2")
g.vrun(9, 17, 47, "2"); g.vrun(55, 17, 47, "2")
# 후드 안 어둠 (얼굴 구멍 — 둥근 모서리)
g.rect(14, 14, 50, 44, "2")
for dx, dy in ((0, 0), (1, 0), (2, 0), (0, 1), (1, 1), (0, 2), (0, 3)):
    g.set(14 + dx, 14 + dy, "4"); g.set(50 - dx, 14 + dy, "4")
    g.set(14 + dx, 44 - dy, "4"); g.set(50 - dx, 44 - dy, "4")
# 후드 스티치 대시 (호박)
for x in range(14, 51, 8):
    g.run(x, x + 2, 8, "9")
# 후드에 붙은 날짜 태그
g.rect(45, 10, 50, 13, "a"); g.run(46, 48, 11, "9"); g.set(46, 12, "9")

# ---------- 얼굴 (후드 속 — 넓고 둥근 모에 페이스) ----------
face = {18: (20, 46), 19: (18, 47), 20: (17, 48)}
for y in range(21, 40):
    face[y] = (17, 48)
face.update({40: (18, 47), 41: (19, 46), 42: (21, 44), 43: (25, 40), 44: (29, 36)})
for y, (x0, x1) in face.items():
    g.run(x0, x1, y, "5")

# ---------- 앞머리 스윕 — 뷰어-좌 눈을 완전히 가림 (감기는 곡선) ----------
sweep = {17: (14, 34), 18: (14, 34), 19: (14, 33), 20: (14, 33), 21: (15, 32),
         22: (15, 31), 23: (15, 31), 24: (16, 30), 25: (16, 29), 26: (17, 28),
         27: (17, 27), 28: (18, 26), 29: (18, 25), 30: (19, 24), 31: (20, 23),
         32: (20, 22), 33: (21, 21)}
for y, (x0, x1) in sweep.items():
    g.run(x0, x1, y, "2")
g.run(24, 27, 17, "4")                                     # 스윕 위 무광 광택 1선

# ---------- 보이는 눈 — 거대한 호박 원반 (졸린 반개 + 반짝임 = 스머그) ----------
# 12×12 (x34..45, y21..32): 윗눈꺼풀이 원반 위를 직선으로 자름
g.blit(34, 21, [
    "222222222222",
    "222222222222",
    "222222222222",
    "29aaaaaaaa92",
    "9aa55222aaa9",
    "9aa55222aaa9",
    "9aaa2222aaa9",
    "9aaaaaaaaaa9",
    "29aaaaaaaa92",
    ".2999999992.",
    "..26666662..",
])
# ---------- 볼터치 (호박 사선) ----------
g.run(18, 21, 36, "a"); g.run(19, 22, 37, "a")
g.run(45, 47, 36, "a")

# ---------- 입 — 스머그 그린 + 송곳니 (헬테이커) ----------
g.run(27, 36, 38, "2")
g.set(26, 37, "2"); g.set(37, 37, "2")                     # 양끝이 살짝 위 (씩 웃음)
g.blit(28, 39, ["5.", "5."])                               # 송곳니 (왼쪽 1개, 2px)
g.set(27, 39, "2"); g.set(30, 39, "2")                     # 송곳니 라인 고정

# ---------- 목·스목 (작게) + 포트·케이블·태그 ----------
g.rect(29, 45, 37, 47, "5")
g.rect(20, 48, 44, 50, "4")
sh = {51: (16, 48), 52: (14, 50), 53: (13, 51)}
for y, (x0, x1) in sh.items():
    g.run(x0, x1, y, "4")
g.rect(12, 54, 52, 63, "4")
g.run(16, 48, 50, "2", over=False)
g.vrun(12, 54, 63, "2"); g.vrun(52, 54, 63, "2")
# 앞섶 스티치
for x in range(20, 45, 8):
    g.run(x, x + 1, 57, "9")
# 목 뒤 포트 (뷰어-좌) → 리본 케이블이 앞을 지나 오른쪽 아래로
g.rect(13, 49, 15, 51, "2"); g.set(14, 50, "a")
path = [(12, 53), (10, 56), (10, 59), (13, 61), (19, 62), (27, 63), (36, 63),
        (44, 62), (51, 60), (56, 57)]
pts = []
for i in range(len(path) - 1):
    x0, y0 = path[i]; x1, y1 = path[i + 1]
    steps = max(abs(x1 - x0), abs(y1 - y0))
    for s in range(steps + 1):
        p = (round(x0 + (x1 - x0) * s / steps), round(y0 + (y1 - y0) * s / steps))
        if p not in pts:
            pts.append(p)
for j, (x, y) in enumerate(pts):
    g.set(x, y, "9"); g.set(x, y + 1, "9")
    if j % 7 in (0, 1):
        g.set(x, y, "a")
# 케이블 끝 커넥터 + 날짜 태그
g.rect(57, 55, 59, 57, "2"); g.set(60, 56, "a")
g.set(48, 61, "9")
g.rect(45, 57, 51, 60, "a"); g.run(46, 49, 58, "9")

g.save(os.path.join(os.path.dirname(__file__), "..", "..", "assets", "px_v2", "por_seek_64.px"),
       "por_seek_64 — 시크 웜 V2 초상 (모에 개정 — 스머그 그린)")
