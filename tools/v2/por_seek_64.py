#!/usr/bin/env python3
# por_seek_64.py — 시크 웜 V2 초상 64×64 (방송용 인간형 아바타 — docs/06 §2, 40 §4)
# 브리지: 호박 버퍼 릴 / 읽히지 않는 한쪽 눈 / 리본 저장 케이블 / 날짜 태그
# 문법: 낮고 감기는 곡선, 케이블이 본체보다 먼저 읽힘, 얼굴 일부 항상 가림
import sys, os, math
sys.path.insert(0, os.path.dirname(__file__))
from pxlib import Grid

g = Grid(64, 64)

# ---------- 깨진 버퍼 링 (배경) — 불규칙한 다중 절단 (에코의 정연함과 대비) ----------
for a0, a1 in ((-30, 40), (75, 150), (195, 260)):
    g.arc(32, 30, 28, a0, a1, "9", dash=(11, 4), thick=2)
for a0, a1 in ((25, 80), (125, 168), (230, 300)):
    g.arc(32, 30, 23, a0, a1, "9", dash=(9, 4), thick=1)
for a0 in (100, 210):
    g.arc(32, 30, 28, a0, a0 + 7, "a", thick=2)          # 보관된 조각 2칸만 점등

# ---------- 후드 (낮고 둥근 실루엣) ----------
hood = {12: (26, 38), 13: (24, 40), 14: (22, 42), 15: (21, 43), 16: (20, 44),
        17: (20, 44), 18: (19, 45)}
for y, (x0, x1) in hood.items():
    g.run(x0, x1, y, "4")
for y in range(19, 46):
    g.run(19, 45, y, "4")
# 후드 안 어둠 (얼굴 구멍보다 넓게)
g.rect(23, 18, 41, 43, "2")

# ---------- 얼굴 (후드 그늘 속 — 오른쪽 절반이 주로 보임) ----------
face = {24: (27, 39), 25: (26, 40), 26: (26, 40)}
for y in range(27, 38):
    face[y] = (25, 40)
face.update({38: (26, 39), 39: (27, 38), 40: (28, 37), 41: (29, 36), 42: (30, 35)})
for y, (x0, x1) in face.items():
    g.run(x0, x1, y, "5")
# 후드 그늘 — 이마 위 1px 어둔 띠
g.run(26, 39, 24, "6")

# ---------- 앞머리 스윕 — 뷰어-좌 눈을 '완전히' 가림 ----------
sweep = {21: (23, 33), 22: (23, 33), 23: (23, 33), 24: (23, 32), 25: (23, 32),
         26: (24, 32), 27: (24, 31), 28: (24, 31), 29: (25, 31), 30: (25, 30),
         31: (26, 30), 32: (27, 30), 33: (28, 29), 34: (28, 28)}
for y, (x0, x1) in sweep.items():
    g.run(x0, x1, y, "2")
g.set(28, 35, "2")                                        # 끝단 (감기는 곡선의 꼬리 — 몸체와 연결)
g.vrun(31, 22, 27, "4")                                   # 스윕 안 광택 1선 (호박이 아닌 무광)

# ---------- 보이는 눈 (호박 삼백안 — 치켜뜬 반개 시선) ----------
g.blit(33, 27, [
    ".22222.",
    "2222222",
    "29aa952",
    "2555552",
    ".66666.",
])
# ---------- 입 — 작은 미소 + 송곳니 1px ----------
g.run(31, 34, 37, "2")
g.set(35, 36, "2")                                        # 입꼬리 상승(뷰어-우)
g.set(31, 38, "5"); g.set(31, 38, "5")                    # 송곳니 (입 왼끝 아래 흰 점)
g.set(30, 38, "6")                                        # 송곳니 옆 그늘로 형태 고정
g.set(32, 34, "6")                                        # 코

# ---------- 스목(작업복) 몸통 — 낮게 웅크린 어깨 ----------
sm = {44: (20, 44), 45: (18, 46), 46: (16, 48), 47: (15, 49)}
for y, (x0, x1) in sm.items():
    g.run(x0, x1, y, "4")
g.rect(14, 48, 50, 63, "4")
g.outline_selout("4", "3")                                # 스목 셀아웃 — 배경 접면만 밝은 에지
# 앞섶 스티치 — 호박 2px 대시 (기록 라벨 문법, 고립 점 금지)
for x in range(20, 43, 6):
    g.run(x, x + 1, 51, "9")
# 후드 턱 아래 그림자
g.run(27, 37, 43, "3")

# ---------- 목 뒤 포트 + 리본 케이블 (시작점 1곳, 굵기 불변, 몸 비관통) ----------
g.rect(21, 43, 23, 45, "2"); g.set(22, 44, "a")           # 포트 커넥터
path = [(20, 47), (18, 50), (17, 53), (17, 56), (19, 59), (23, 61), (28, 62),
        (34, 62), (40, 61), (45, 59), (49, 57), (52, 55)]
pts = []
for i in range(len(path) - 1):
    x0, y0 = path[i]; x1, y1 = path[i + 1]
    steps = max(abs(x1 - x0), abs(y1 - y0))
    for s in range(steps + 1):
        x = round(x0 + (x1 - x0) * s / steps)
        y = round(y0 + (y1 - y0) * s / steps)
        if (x, y) not in pts:
            pts.append((x, y))
for j, (x, y) in enumerate(pts):
    g.set(x, y, "9"); g.set(x, y + 1, "9")                # 리본 2px — 굵기 불변
    if j % 7 in (0, 1):
        g.set(x, y, "a")                                  # 하이라이트는 간헐적 상단 픽셀만
# 케이블 끝 커넥터 — 본체보다 늦게 사라지는 그 끝
g.rect(53, 53, 55, 55, "2"); g.set(56, 54, "a")

# ---------- 날짜 태그 (케이블에 매달림 — '여러 날짜의 같은 장면') ----------
g.set(44, 60, "9")                                        # 태그 끈
g.rect(41, 56, 47, 59, "a")
g.run(42, 45, 57, "9")                                    # 날짜 대시
# 후드에 붙은 소형 태그 (다른 날짜, 같은 장면)
g.rect(40, 16, 43, 18, "a"); g.run(41, 42, 17, "9")

g.save(os.path.join(os.path.dirname(__file__), "..", "..", "assets", "px_v2", "por_seek_64.px"),
       "por_seek_64 — 시크 웜 V2 초상 (방송용 인간형 아바타)")
