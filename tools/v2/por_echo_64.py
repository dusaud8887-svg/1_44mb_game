#!/usr/bin/env python3
# por_echo_64.py — 에코 일사사 V2 초상 64×64 (모에 개정판)
# 스타일 기준: ABM '차원통신'(거대 원반 홍채·벌린 입·볼터치·통신장비 모에화) +
#             헬테이커(두꺼운 라인·플랫 셀·큰 머리 실루엣). docs/06 브리지 유지:
#             끊긴 청록 링 / 비대칭 머리 / 빨간 LIVE 핀 / 한쪽 수신기 / 눈썹 1px 차 / 입 오프셋
import sys, os
sys.path.insert(0, os.path.dirname(__file__))
from pxlib import Grid

g = Grid(64, 64)

# ---------- 끊긴 64링 (배경 — 우상단 끊김, 3칸 점등) ----------
g.arc(32, 30, 30, -14, 262, "7", dash=(14, 5), thick=2)
for a0 in (205, 230, 255):
    g.arc(32, 30, 30, a0, a0 + 8, "8", thick=2)

# ---------- 머리카락 큰 덩어리 (헬테이커식 실루엣 — 검은 외곽선) ----------
# 바깥 윤곽(2) 안에 청록(8) 플랫 — 비대칭: 뷰어-좌로 긴 머리채
hair = {4: (22, 42), 5: (18, 46), 6: (16, 49), 7: (14, 51), 8: (13, 52),
        9: (12, 53), 10: (11, 54), 11: (10, 55), 12: (10, 55), 13: (9, 56),
        14: (9, 56), 15: (8, 56), 16: (8, 57), 17: (8, 57), 18: (8, 57),
        19: (8, 57), 20: (8, 57), 21: (8, 57), 22: (9, 57), 23: (9, 56),
        24: (9, 56), 25: (10, 56), 26: (10, 55), 27: (11, 55)}
for y, (x0, x1) in hair.items():
    g.run(x0, x1, y, "8")
# 옆머리 기둥 (얼굴 좌우 프레임)
for y in range(28, 46):
    g.run(10, 15, y, "8")
    g.run(50, 55, y, "8")
# 긴 머리채 (뷰어-좌, 하단 밖까지 — 비대칭 훅)
for y in range(46, 64):
    x0 = 9 + (y - 46) // 5
    g.run(x0, x0 + 6, y, "8")
# 머리 그림자 톤 (플랫 1단만 — 옆머리 안쪽)
for y in range(28, 46):
    g.run(14, 15, y, "7"); g.run(50, 51, y, "7")
for y in range(46, 64):
    x0 = 9 + (y - 46) // 5
    g.run(x0 + 4, x0 + 6, y, "7")
g.run(16, 20, 6, "5")                                      # 정수리 하이라이트 획 2개
g.run(24, 30, 5, "5")

# ---------- 얼굴 (넓고 둥근 모에 페이스 — 뺨이 부풀고 턱은 완만) ----------
face = {16: (20, 46), 17: (18, 48), 18: (17, 49), 19: (16, 50)}
for y in range(20, 40):
    face[y] = (16, 50)
face.update({40: (17, 49), 41: (18, 48), 42: (20, 46), 43: (23, 43), 44: (27, 39)})
for y, (x0, x1) in face.items():
    g.run(x0, x1, y, "5")

# ---------- 앞머리 (크고 단순한 갈래 — 이마를 확실히 덮음) ----------
fringe = {12: (10, 55), 13: (10, 55), 14: (10, 55), 15: (10, 55), 16: (10, 55),
          17: (10, 55), 18: (10, 54)}
for y, (x0, x1) in fringe.items():
    g.run(x0, x1, y, "8")
# 갈래 끝(뾰족) — 좌가 길고 우가 짧은 비대칭, 눈썹 라인까지 깊게
tips = [(10, 16, 19), (11, 16, 20), (12, 15, 21), (13, 14, 22),
        (17, 23, 19), (18, 22, 20), (19, 21, 21), (20, 20, 22),
        (24, 30, 19), (25, 29, 20), (26, 28, 21), (27, 27, 22),
        (31, 36, 18), (32, 35, 19), (33, 34, 20),
        (37, 42, 18), (38, 41, 19), (39, 40, 20),
        (43, 49, 18), (44, 48, 19), (45, 47, 20), (50, 54, 18), (51, 53, 19)]
for x0, x1, y in tips:
    g.run(x0, x1, y, "8")
# 아호게 (신호 수신 안테나 — 한 가닥이 위로 튐)
g.set(38, 3, "8"); g.set(39, 2, "8"); g.set(40, 1, "8"); g.set(41, 1, "8")
g.set(42, 2, "8"); g.set(41, 0, "7")

# ---------- 눈썹 (한쪽 1px 높음) ----------
g.run(19, 25, 21, "2")                                     # 뷰어-좌
g.run(37, 44, 20, "2")                                     # 뷰어-우 (1px 높음)

# ---------- 눈 — ABM식 거대 원반 홍채 (얼굴의 1/3) ----------
# 뷰어-좌 눈 11×13 (x18..28, y23..35)
g.blit(18, 23, [
    ".222222222.",
    "22222222222",
    "22222222222",
    "25788887752",
    "27888888872",
    "78882222887",
    "78822222287",
    "78855222287",
    "78855222287",
    "78822222287",
    ".788888887.",
    ".277777772.",
    "..2666662..",
])
# 뷰어-우 눈 12×14 (x36..47, y22..35) — 근안이 1px 큼
g.blit(36, 22, [
    ".2222222222.",
    "222222222222",
    "222222222222",
    "257888887752",
    "278888888872",
    "788822228887",
    "788222222287",
    "788552222287",
    "788552222287",
    "788222222287",
    "278888888872",
    ".2777777772.",
    "..26666662..",
    "............",
])

# ---------- 볼터치 (모에 필수 — DIM 사선 패치) ----------
g.run(16, 19, 38, "6"); g.run(17, 20, 39, "6")
g.run(47, 50, 38, "6"); g.run(46, 49, 39, "6")

# ---------- 입 — 크게 벌린 방송 미소 (중심 1px 오프셋, 한쪽 꼬리만 위) ----------
g.blit(27, 38, [
    "22222222",
    "2bbbbbb2",
    "2bbbbb2.",
    ".2bbb2..",
    "..222...",
])
g.set(35, 37, "2")                                         # 오른쪽 입꼬리 상승
g.run(28, 33, 39, "5")                                     # 윗니 하이라이트

# ---------- 한쪽 수신기 + 신호 파형 칩 (차원통신 오마주) ----------
g.blit(51, 26, [
    ".222.",
    "22222",
    "28882",
    "28282",
    "28882",
    "22222",
    ".222.",
])
g.set(52, 29, "5")                                         # 파형 점
g.set(50, 24, "2"); g.set(51, 25, "2")                     # 밴드

# ---------- 목·몸 (작게 — 치비 비율) + 재킷·LIVE 핀 ----------
g.rect(29, 45, 37, 48, "5")
g.run(30, 36, 45, "6")                                     # 턱 그림자 1선
g.rect(24, 49, 42, 50, "2")                                # 하이넥
sh = {51: (20, 46), 52: (17, 49), 53: (15, 51), 54: (14, 52)}
for y, (x0, x1) in sh.items():
    g.run(x0, x1, y, "5")
g.rect(13, 55, 53, 63, "5")
# 어깨 외곽선
g.run(20, 46, 50, "2", over=False)
for y, (x0, x1) in sh.items():
    g.set(x0, y, "2"); g.set(x1, y, "2")
g.vrun(13, 55, 63, "2"); g.vrun(53, 55, 63, "2")
# 안감 V + 라펠 (좌 직선 / 우 원호 끊김)
for y in range(51, 64):
    w = max(1, 5 - (y - 51) // 3)
    g.run(33 - w // 2, 33 + w - w // 2 - 1, y, "2")
for i, y in enumerate(range(51, 64)):
    g.set(27 - i // 4, y, "6")
for y, x in {51: 39, 53: 40, 55: 41, 59: 42, 61: 42, 63: 41}.items():
    g.set(x, y, "6")                                       # y57 갭 = 끊긴 원호
for y in (52, 55, 58, 61):
    g.set(44, y, "8")                                      # CUE 탭
# LIVE 핀 — 유일한 빨강 강조
g.rect(24, 53, 25, 54, "d")
# 한쪽 소매만 청록
for y in range(58, 64):
    g.run(47, 53, y, "8")
g.vrun(47, 58, 63, "7")

g.save(os.path.join(os.path.dirname(__file__), "..", "..", "assets", "px_v2", "por_echo_64.px"),
       "por_echo_64 — 에코 일사사 V2 초상 (모에 개정 — 방송 미소)")
