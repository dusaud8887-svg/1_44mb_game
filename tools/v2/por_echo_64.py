#!/usr/bin/env python3
# por_echo_64.py — 에코 일사사 V2 초상 64×64 (docs/06 §1, 40 §4, 41 §2)
# 브리지: 끊긴 청록 링(우상단 끊김 통일) / 비대칭 머리 / 빨간 LIVE 핀 / 한쪽 수신기
# 얼굴 규칙: 양눈 비동일 / 한쪽 눈썹 1px 높음 / 입 중심 1px 오프셋·한쪽 입꼬리만 상승
import sys, os
sys.path.insert(0, os.path.dirname(__file__))
from pxlib import Grid

g = Grid(64, 64)

# ---------- 뒷머리 레이어 (링보다 앞, 얼굴보다 뒤) ----------
# 좌측(뷰어 기준) 긴 머리채 — 어깨를 지나 하단까지 S커브
long_lock = {  # y: (x0, x1)
    **{y: (17, 23) for y in range(14, 22)},
    **{y: (16, 23) for y in range(22, 28)},
    **{y: (15, 22) for y in range(28, 34)},
    **{y: (14, 21) for y in range(34, 42)},
    **{y: (14, 21) for y in range(42, 48)},
    **{y: (15, 22) for y in range(48, 55)},
    **{y: (16, 23) for y in range(55, 60)},
    **{y: (17, 23) for y in range(60, 64)},
}
for y, (x0, x1) in long_lock.items():
    g.run(x0, x1, y, "8")
# 우측 짧은 머리(귀 뒤로 넘김) — 얇은 안쪽 그림자 머리, 어깨선까지 테이퍼
for y in range(14, 42):
    if y < 26:
        g.run(43, 46, y, "8")
    elif y < 36:
        g.run(43, 45, y, "8")
    else:
        g.run(43, 44, y, "8")

# ---------- 두상·앞머리 ----------
head_top = {5: (27, 37), 6: (25, 39), 7: (23, 41), 8: (22, 42), 9: (21, 43),
            10: (20, 44), 11: (19, 44), 12: (19, 45), 13: (18, 45)}
for y, (x0, x1) in head_top.items():
    g.run(x0, x1, y, "8")
for y in range(14, 21):  # 이마 옆 프레임
    g.run(18, 46, y, "8")

# ---------- 얼굴 피부 ----------
face = {20: (26, 40), 21: (25, 41), 22: (25, 41), 23: (24, 41), 24: (24, 41),
        25: (23, 41), 26: (23, 41), 27: (23, 41), 28: (23, 41), 29: (23, 41),
        30: (23, 41), 31: (23, 41), 32: (24, 41), 33: (24, 41), 34: (24, 40),
        35: (24, 40), 36: (25, 39), 37: (25, 39), 38: (26, 38), 39: (27, 37),
        40: (28, 36), 41: (29, 35), 42: (30, 34)}
for y, (x0, x1) in face.items():
    g.run(x0, x1, y, "5")

# ---------- 앞머리(бangs) — 오른쪽 가르마에서 왼쪽으로 스윕 ----------
bangs = {
    14: (18, 46), 15: (18, 46), 16: (18, 46), 17: (18, 45), 18: (18, 44),
    19: (18, 42),
}
for y, (x0, x1) in bangs.items():
    g.run(x0, x1, y, "8")
# 앞머리 밑단 — 왼쪽이 길고 오른쪽이 짧은 사선 톱니 (클러스터 단위, 끝이 뾰족하게)
fringe = [
    # (x0, x1, y) 덩어리 끝단
    (18, 21, 20), (18, 20, 21), (18, 19, 22), (19, 19, 23),
    (22, 25, 20), (22, 24, 21), (23, 24, 22), (23, 23, 23), (23, 23, 24),
    (26, 29, 20), (26, 28, 21), (27, 27, 22), (27, 27, 23),
    (30, 33, 19), (30, 32, 20), (31, 31, 21), (31, 31, 22),
    (34, 36, 19), (35, 35, 20), (35, 35, 21),
    (37, 39, 18), (38, 38, 19), (38, 38, 20),
    (40, 42, 17), (41, 41, 18),
]
for x0, x1, y in fringe:
    g.run(x0, x1, y, "8")
# 앞머리 그림자 — 가장 긴 두 갈래 아래 피부 위에만 짧게 (over=False로 피부 위만)
for x0, x1, y in [(24, 25, 25), (30, 32, 23)]:
    for x in range(x0, x1 + 1):
        if g.get(x, y) == "5":
            g.set(x, y, "6")

# 머리 음영(청록 어두운 면 — 큰 클러스터로)
for y, (x0, x1) in long_lock.items():
    g.run(x0, x0 + 1, y, "7")          # 긴 머리채 안쪽
for y in range(14, 42):                 # 우측 뒷머리는 전부 그림자 톤
    if y < 26:
        g.run(43, 46, y, "7")
    elif y < 36:
        g.run(43, 45, y, "7")
    else:
        g.run(43, 44, y, "7")
for y, (x0, x1) in head_top.items():    # 정수리 하이라이트는 남기고 옆면만
    g.run(x1 - 1, x1, y, "7")
g.run(18, 19, 15, "7"); g.run(18, 19, 16, "7"); g.run(18, 18, 17, "7")

# ---------- 눈·눈썹 (리터럴 — 뷰어 우측 눈이 근안·1px 큼, 눈썹 1px 높음) ----------
# 뷰어-좌(원안, 6폭): x24..29
g.blit(24, 23, [
    "777777",      # 눈썹 y23
])
g.blit(24, 25, [
    ".2222.",
    "222222",
    "258882",
    "252882",
    "272872",
    "277772",
    ".6666.",
])
# 뷰어-우(근안, 7폭): x34..40, 눈썹 y22 (1px 높음)
g.blit(34, 22, [
    "7777777",
])
g.blit(34, 24, [
    ".22222.",
    "2222222",
    "2558882",
    "2528822",
    "2728872",
    "2777772",
    ".66666.",
])

# ---------- 코·입 ----------
g.set(32, 34, "6")                       # 코 — 점 하나 (입 중심선과 정렬)
g.run(30, 33, 37, "2")                   # 입 (중심 32에서 좌로 1px 오프셋)
g.set(34, 36, "2")                       # 오른쪽 입꼬리만 상승
g.run(31, 33, 38, "6")                   # 아랫입술 그림자

# ---------- 헤드셋(한쪽 수신기 — 뷰어 우측, 둥근 컵 + 수신광) ----------
g.blit(42, 28, [
    ".22.",
    "2222",
    "2282",
    "2282",
    "2222",
    ".22.",
])
g.set(44, 26, "2"); g.set(45, 27, "2")   # 밴드가 머리 위로
g.vrun(41, 29, 32, "6")                  # 컵 림 — 어두운 머리와 분리

# ---------- 목·칼라·어깨 ----------
g.rect(29, 43, 35, 47, "5")
g.run(31, 34, 43, "6"); g.run(31, 33, 44, "6")   # 턱 그림자 (좁게)
# 뒷머리 채움 — 얼굴 옆·목 뒤 배경 노출 방지 (투명한 곳만)
for y in range(19, 49):
    g.run(19, 25, y, "7", over=False)
    g.run(39, 43, y, "7", over=False)
# 검은 하이넥
g.rect(27, 47, 37, 49, "2")
g.run(28, 36, 46, "2", over=False)
# 어깨(재킷 흰색) — 좌우로 벌어짐
sh = {49: (20, 45), 50: (17, 48), 51: (15, 50), 52: (13, 52), 53: (12, 53),
      54: (11, 54), 55: (10, 55)}
for y, (x0, x1) in sh.items():
    g.run(x0, x1, y, "5", over=False)
g.rect(10, 56, 55, 63, "5", over=False)
# 옷깃 V (안감 검정)
v = {49: (29, 35), 50: (29, 35), 51: (30, 34), 52: (30, 34), 53: (30, 34),
     54: (31, 33), 55: (31, 33), 56: (31, 33)}
for y, (x0, x1) in v.items():
    g.run(x0, x1, y, "2")
g.rect(31, 57, 33, 63, "2")
# 좌 라펠 = 직선 (에지 6)
for i, y in enumerate(range(49, 64)):
    g.set(28 - i // 3, y, "6")
# 우 라펠 = 끊긴 원호 (에지 6, y55~56 갭 = '끊긴 링' 문법)
arcx = {49: 36, 50: 37, 51: 38, 52: 38, 53: 39, 54: 39, 57: 40, 58: 40,
        59: 40, 60: 39, 61: 39, 62: 38, 63: 38}
for y, x in arcx.items():
    g.set(x, y, "6")
# CUE 탭 5개 — 우 라펠 바깥에 청록 틱
for y in (50, 52, 54, 58, 60):
    x = arcx.get(y, 39) + 2
    g.set(x, y, "8"); g.set(x + 1, y, "7")
# 한쪽 소매만 청록 (뷰어 우측 어깨)
for y in range(52, 64):
    x0 = max(46, 52 - (y - 52) * 2)
    g.run(x0, 55, y, "8")
    g.run(x0, x0 + 1, y, "7")
# LIVE 핀 — 좌 라펠 위 빨강 (화면에서 유일한 빨강)
g.rect(24, 51, 25, 52, "d")
g.set(26, 52, "6")

# ---------- 긴 머리채를 어깨 위에 다시 얹기 ----------
for y in range(48, 64):
    x0, x1 = long_lock[min(y, 63)]
    g.run(x0, x1, y, "8")
    g.run(x0, x0 + 1, y, "7")
# 머리채 끝단 갈라짐
g.blit(15, 60, [
    "88.888",
    "8..88.",
    "7..8..",
    "7..7..",
])

# ---------- 끊긴 64링 (배경 레이어 — 우상단 끊김) ----------
# 본체 뒤로만 (under=True), 세그먼트 대시. 끊긴 구간: -80°..-15° (우상단)
g.arc(33, 27, 29, -15, 265, "7", dash=(14, 5), thick=2, under=True)
# 수신된 메아리 3칸 점등 (좌상단 가시 구간 — 밝은 청록)
for a0 in (200, 225, 250):
    g.arc(33, 27, 29, a0, a0 + 8, "8", thick=2, under=True)
# 링 끊긴 단면 강조
g.set(60, 20, "8"); g.set(59, 16, "7")

g.save(os.path.join(os.path.dirname(__file__), "..", "..", "assets", "px_v2", "por_echo_64.px"),
       "por_echo_64 — 에코 일사사 V2 초상 (기본 진행 표정)")
